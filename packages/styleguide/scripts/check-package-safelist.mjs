#!/usr/bin/env node
// scripts/check-package-safelist.mjs
//
// Presence guard for dist/safelist.css — run as part of `pnpm check` so a
// build that missed the tsup onSuccess step (which runs gen-safelist.mjs)
// fails loudly instead of shipping a package whose `./safelist.css` export
// 404s for consumers.
//
// Model: @takazudo/zudo-doc's scripts/check-safelist.mjs.
//
// Exit 0 → dist/safelist.css exists, is non-empty, and starts with a single
//          @source inline(...) directive (drift guard: a stale hand-edit or
//          a generator regression would fail this shape check).
// Exit 1 → missing, empty, or malformed (with a clear diagnostic message).

import { statSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SAFELIST = resolve(__dirname, "../dist/safelist.css");

let size = 0;
try {
  size = statSync(SAFELIST).size;
} catch {
  console.error(
    "\n[check-package-safelist] ERROR: dist/safelist.css is missing.\n" +
      "  Run `pnpm --filter @takazudo/zudo-sg build` first so the tsup\n" +
      "  onSuccess hook generates the file, then retry.\n",
  );
  process.exit(1);
}

if (size === 0) {
  console.error(
    "\n[check-package-safelist] ERROR: dist/safelist.css exists but is empty.\n" +
      "  The tsup onSuccess hook (gen-safelist.mjs) may have failed silently.\n" +
      "  Re-run `pnpm --filter @takazudo/zudo-sg build` and check for errors.\n",
  );
  process.exit(1);
}

const content = readFileSync(SAFELIST, "utf8");
if (!/@source inline\("[^"]*"\);/.test(content)) {
  console.error(
    "\n[check-package-safelist] ERROR: dist/safelist.css does not contain a\n" +
      '  well-formed "@source inline(\\"…\\");" directive. It was probably\n' +
      "  hand-edited or generated by a stale version of gen-safelist.mjs.\n" +
      "  Re-run `pnpm --filter @takazudo/zudo-sg build`.\n",
  );
  process.exit(1);
}

console.log(`[check-package-safelist] dist/safelist.css OK (${size} bytes)`);
